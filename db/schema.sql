-- ATM cash replenishment and downtime ledger.
-- Applied automatically on startup. Safe to re-run.

CREATE TABLE IF NOT EXISTS app_meta (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS locations (
  location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_code VARCHAR(10) NOT NULL UNIQUE,
  location_name VARCHAR(100) NOT NULL,
  city VARCHAR(80) NOT NULL,
  state VARCHAR(80) NOT NULL,
  region VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS branches (
  branch_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id INTEGER NOT NULL REFERENCES locations (location_id),
  branch_code VARCHAR(16) NOT NULL UNIQUE,
  branch_name VARCHAR(120) NOT NULL,
  address VARCHAR(240) NOT NULL,
  ifsc_code VARCHAR(11) NOT NULL
);

CREATE TABLE IF NOT EXISTS atms (
  atm_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id INTEGER NOT NULL REFERENCES branches (branch_id),
  atm_code VARCHAR(20) NOT NULL UNIQUE,
  site_name VARCHAR(120) NOT NULL,
  address VARCHAR(240) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('active', 'cash_out', 'out_of_service', 'decommissioned')),
  installed_on DATE NOT NULL,
  cassette_count SMALLINT NOT NULL DEFAULT 4 CHECK (cassette_count BETWEEN 1 AND 4),
  capacity_amount NUMERIC(14,2) NOT NULL CHECK (capacity_amount > 0),
  current_cash NUMERIC(14,2) NOT NULL CHECK (current_cash >= 0),
  last_replenished_on DATE,
  CONSTRAINT atms_cash_within_capacity CHECK (current_cash <= capacity_amount)
);

CREATE TABLE IF NOT EXISTS cash_vans (
  van_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id INTEGER NOT NULL REFERENCES locations (location_id),
  van_code VARCHAR(16) NOT NULL UNIQUE,
  registration_no VARCHAR(20) NOT NULL UNIQUE,
  capacity_amount NUMERIC(14,2) NOT NULL CHECK (capacity_amount > 0),
  status VARCHAR(20) NOT NULL CHECK (status IN ('available', 'on_route', 'maintenance'))
);

CREATE TABLE IF NOT EXISTS custodians (
  custodian_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  van_id INTEGER REFERENCES cash_vans (van_id),
  employee_code VARCHAR(16) NOT NULL UNIQUE,
  full_name VARCHAR(120) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS engineers (
  engineer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id INTEGER NOT NULL REFERENCES locations (location_id),
  employee_code VARCHAR(16) NOT NULL UNIQUE,
  full_name VARCHAR(120) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  specialty VARCHAR(24) NOT NULL CHECK (specialty IN ('hardware', 'network', 'cash_handling', 'general')),
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS replenishment_runs (
  run_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  van_id INTEGER NOT NULL REFERENCES cash_vans (van_id),
  custodian_id INTEGER NOT NULL REFERENCES custodians (custodian_id),
  location_id INTEGER NOT NULL REFERENCES locations (location_id),
  planned_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('planned', 'in_progress', 'completed', 'cancelled')),
  notes TEXT,
  created_by VARCHAR(40) NOT NULL DEFAULT 'planner',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cassette_loads (
  load_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id INTEGER NOT NULL REFERENCES replenishment_runs (run_id) ON DELETE CASCADE,
  atm_id INTEGER NOT NULL REFERENCES atms (atm_id),
  cassette_number SMALLINT NOT NULL CHECK (cassette_number BETWEEN 1 AND 4),
  denomination NUMERIC(10,2) NOT NULL CHECK (denomination IN (100, 200, 500, 2000)),
  note_count INTEGER NOT NULL CHECK (note_count > 0 AND note_count <= 10000),
  amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  loaded_at TIMESTAMPTZ,
  CONSTRAINT cassette_loads_amount_product CHECK (amount = denomination * note_count),
  CONSTRAINT cassette_loads_unique_slot UNIQUE (run_id, atm_id, cassette_number)
);

CREATE TABLE IF NOT EXISTS daily_withdrawals (
  withdrawal_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atm_id INTEGER NOT NULL REFERENCES atms (atm_id),
  withdrawal_date DATE NOT NULL,
  amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  txn_count INTEGER NOT NULL CHECK (txn_count >= 0),
  source VARCHAR(20) NOT NULL DEFAULT 'seed' CHECK (source IN ('seed', 'switch', 'manual')),
  CONSTRAINT daily_withdrawals_atm_date UNIQUE (atm_id, withdrawal_date)
);

CREATE TABLE IF NOT EXISTS reconciliations (
  reconciliation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atm_id INTEGER NOT NULL REFERENCES atms (atm_id),
  run_id INTEGER REFERENCES replenishment_runs (run_id) ON DELETE SET NULL,
  recon_date DATE NOT NULL,
  expected_amount NUMERIC(14,2) NOT NULL,
  counted_amount NUMERIC(14,2) NOT NULL,
  difference NUMERIC(14,2) GENERATED ALWAYS AS (counted_amount - expected_amount) STORED,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE SEQUENCE IF NOT EXISTS fault_ticket_no_seq;

CREATE TABLE IF NOT EXISTS fault_tickets (
  ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_no VARCHAR(16) NOT NULL UNIQUE DEFAULT ('TKT-' || lpad(nextval('fault_ticket_no_seq')::text, 6, '0')),
  atm_id INTEGER NOT NULL REFERENCES atms (atm_id),
  reconciliation_id INTEGER REFERENCES reconciliations (reconciliation_id),
  engineer_id INTEGER REFERENCES engineers (engineer_id) ON DELETE SET NULL,
  title VARCHAR(200) NOT NULL,
  description TEXT,
  category VARCHAR(24) NOT NULL CHECK (category IN ('cash_variance', 'cash_out', 'hardware', 'communication', 'cassette_error')),
  priority VARCHAR(12) NOT NULL CHECK (priority IN ('low', 'medium', 'high', 'critical')),
  status VARCHAR(12) NOT NULL CHECK (status IN ('open', 'assigned', 'closed')),
  source VARCHAR(12) NOT NULL CHECK (source IN ('trigger', 'manual', 'monitor')),
  resolution TEXT,
  opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  assigned_at TIMESTAMPTZ,
  closed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS downtime_log (
  downtime_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atm_id INTEGER NOT NULL REFERENCES atms (atm_id),
