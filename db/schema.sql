  started_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ,
  reason VARCHAR(24) NOT NULL CHECK (reason IN ('cash_out', 'hardware', 'communication', 'power', 'cassette_error', 'vandalism')),
  notes TEXT,
  CONSTRAINT downtime_log_window CHECK (ended_at IS NULL OR ended_at >= started_at)
