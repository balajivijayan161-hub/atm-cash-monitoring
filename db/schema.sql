CREATE OR REPLACE FUNCTION forecast_multiplier(p_date DATE)
RETURNS NUMERIC
LANGUAGE plpgsql
STABLE
AS $fn$
DECLARE
  v_last INTEGER;
  v_day INTEGER;
  v_factor NUMERIC := 1;
  v_holiday NUMERIC;
BEGIN
  IF p_date IS NULL THEN
    RETURN 1;
  END IF;
  v_day := EXTRACT(DAY FROM p_date);
  v_last := EXTRACT(DAY FROM (date_trunc('month', p_date) + INTERVAL '1 month - 1 day')::date);
  IF v_day <= 3 OR v_day > v_last - 2 THEN
    v_factor := v_factor * 1.20;
  END IF;
  IF v_day = v_last THEN
    v_factor := v_factor * 1.15;
  END IF;
  SELECT MAX(multiplier) INTO v_holiday FROM holidays WHERE holiday_date = p_date AND active;
  IF v_holiday IS NOT NULL THEN
    v_factor := v_factor * v_holiday;
  END IF;
  RETURN ROUND(v_factor, 2);
END;
$fn$;

CREATE OR REPLACE FUNCTION forecast_cash(p_atm_id INTEGER, p_target_date DATE)
RETURNS NUMERIC
LANGUAGE plpgsql
STABLE
AS $fn$
DECLARE
  v_forecast NUMERIC(14,2);
BEGIN
  IF p_atm_id IS NULL OR p_target_date IS NULL THEN
    RAISE EXCEPTION 'forecast_cash requires atm_id and target_date';
  END IF;

  SELECT ROUND(COALESCE(AVG(amount), 0) * forecast_multiplier(p_target_date), 2)
    INTO v_forecast
  FROM daily_withdrawals
  WHERE atm_id = p_atm_id
    AND withdrawal_date >= (p_target_date - 28)
    AND withdrawal_date < p_target_date
    AND EXTRACT(DOW FROM withdrawal_date) = EXTRACT(DOW FROM p_target_date);

  RETURN COALESCE(v_forecast, 0);
END;
$fn$;

