CREATE OR REPLACE FUNCTION forecast_cash(p_atm_id INTEGER, p_target_date DATE)
RETURNS NUMERIC
LANGUAGE plpgsql
STABLE
AS $fn$
DECLARE
  v_forecast NUMERIC(14,2);
BEGIN
  IF p_atm_id IS NULL OR p_target_date IS NULL THEN
    RAISE EXCEPTION 'forecast_cash requires atm_id and target_date';
  END IF;

  -- Same weekday over the prior 28 days: four observations when history is complete.
  SELECT ROUND(AVG(amount), 2)
    INTO v_forecast
  FROM daily_withdrawals
  WHERE atm_id = p_atm_id
    AND withdrawal_date >= (p_target_date - 28)
    AND withdrawal_date < p_target_date
    AND EXTRACT(DOW FROM withdrawal_date) = EXTRACT(DOW FROM p_target_date);

  RETURN COALESCE(v_forecast, 0);
END;
$fn$;

COMMENT ON FUNCTION forecast_cash(INTEGER, DATE) IS
  'Cash need for an ATM on a date: average withdrawal on the same weekday across the previous 28 days.';

CREATE OR REPLACE FUNCTION forecast_cash_points(p_atm_id INTEGER, p_target_date DATE)
RETURNS TABLE (
  withdrawal_date DATE,
  amount NUMERIC,
  txn_count INTEGER
)
LANGUAGE sql
STABLE
AS $fn$
  SELECT w.withdrawal_date, w.amount, w.txn_count
  FROM daily_withdrawals w
  WHERE w.atm_id = p_atm_id
    AND w.withdrawal_date >= (p_target_date - 28)
    AND w.withdrawal_date < p_target_date
    AND EXTRACT(DOW FROM w.withdrawal_date) = EXTRACT(DOW FROM p_target_date)
  ORDER BY w.withdrawal_date;
$fn$;

CREATE OR REPLACE PROCEDURE plan_replenishment_routes(
  p_target_date DATE,
  p_location_id INTEGER,
  INOUT p_runs_created INTEGER,
  INOUT p_atms_assigned INTEGER
)
LANGUAGE plpgsql
AS $proc$
DECLARE
  r RECORD;
  v_forecast NUMERIC(14,2);
  v_run_id INTEGER;
  v_van_id INTEGER;
  v_custodian_id INTEGER;
  v_target_fill NUMERIC(14,2);
  v_shortfall INTEGER;
  v_rem INTEGER;
  v_n100 INTEGER;
  v_n200 INTEGER;
  v_n500 INTEGER;
  v_n2000 INTEGER;
BEGIN
  p_runs_created := 0;
  p_atms_assigned := 0;

  IF p_target_date IS NULL THEN
    RAISE EXCEPTION 'plan_replenishment_routes requires a target date';
  END IF;

  FOR r IN
    SELECT a.atm_id, a.current_cash, a.capacity_amount, b.location_id
    FROM atms a
    JOIN branches b ON b.branch_id = a.branch_id
    WHERE a.status IN ('active', 'cash_out')
      AND (p_location_id IS NULL OR b.location_id = p_location_id)
    ORDER BY b.location_id, a.atm_id
  LOOP
    IF EXISTS (
      SELECT 1
      FROM cassette_loads cl
      JOIN replenishment_runs rr ON rr.run_id = cl.run_id
      WHERE cl.atm_id = r.atm_id
        AND rr.planned_date = p_target_date
        AND rr.status <> 'cancelled'
    ) THEN
      CONTINUE;
    END IF;

    v_forecast := forecast_cash(r.atm_id, p_target_date);
    IF v_forecast <= r.current_cash THEN
      CONTINUE;
    END IF;

    v_target_fill := LEAST(r.capacity_amount, GREATEST(v_forecast * 4, r.current_cash));
    v_shortfall := FLOOR(v_target_fill - r.current_cash)::INTEGER;
    IF r.current_cash + v_shortfall > r.capacity_amount THEN
      v_shortfall := FLOOR(r.capacity_amount - r.current_cash)::INTEGER;
    END IF;
    IF v_shortfall < 100 THEN
      CONTINUE;
    END IF;

    v_n2000 := FLOOR(v_shortfall / 2000)::INTEGER;
    v_rem := v_shortfall - (v_n2000 * 2000);
    v_n500 := FLOOR(v_rem / 500)::INTEGER;
    v_rem := v_rem - (v_n500 * 500);
    v_n200 := FLOOR(v_rem / 200)::INTEGER;
    v_rem := v_rem - (v_n200 * 200);
    v_n100 := FLOOR(v_rem / 100)::INTEGER;

    IF v_n100 = 0 AND v_n200 = 0 AND v_n500 = 0 AND v_n2000 = 0 THEN
      CONTINUE;
    END IF;

    v_van_id := NULL;
    SELECT cv.van_id
      INTO v_van_id
    FROM cash_vans cv
    WHERE cv.location_id = r.location_id
      AND cv.status <> 'maintenance'
    ORDER BY (
      SELECT COUNT(DISTINCT cl.atm_id)
      FROM replenishment_runs rr
      JOIN cassette_loads cl ON cl.run_id = rr.run_id
      WHERE rr.van_id = cv.van_id
        AND rr.planned_date = p_target_date
        AND rr.status <> 'cancelled'
    ), cv.van_id
    LIMIT 1;

    IF v_van_id IS NULL THEN
      CONTINUE;
    END IF;

    v_custodian_id := NULL;
    SELECT c.custodian_id
      INTO v_custodian_id
    FROM custodians c
    WHERE c.van_id = v_van_id
      AND c.active
    ORDER BY c.custodian_id
    LIMIT 1;

    IF v_custodian_id IS NULL THEN
      CONTINUE;
    END IF;

    v_run_id := NULL;
    SELECT rr.run_id
      INTO v_run_id
    FROM replenishment_runs rr
    WHERE rr.van_id = v_van_id
      AND rr.planned_date = p_target_date
      AND rr.location_id = r.location_id
      AND rr.status = 'planned'
      AND (
        SELECT COUNT(DISTINCT cl.atm_id)
        FROM cassette_loads cl
        WHERE cl.run_id = rr.run_id
      ) < 15
    ORDER BY rr.run_id
    LIMIT 1;

    IF v_run_id IS NULL THEN
      INSERT INTO replenishment_runs (
        van_id, custodian_id, location_id, planned_date, status, notes, created_by
      ) VALUES (
        v_van_id,
        v_custodian_id,
        r.location_id,
        p_target_date,
        'planned',
        'Auto-planned where forecast_cash exceeds cash still in the machine.',
        'plan_replenishment_routes'
      )
      RETURNING run_id INTO v_run_id;
      p_runs_created := p_runs_created + 1;
    END IF;

    IF v_n100 > 0 THEN
      INSERT INTO cassette_loads (run_id, atm_id, cassette_number, denomination, note_count, amount)
      VALUES (v_run_id, r.atm_id, 1, 100, v_n100, v_n100 * 100);
    END IF;
    IF v_n200 > 0 THEN
      INSERT INTO cassette_loads (run_id, atm_id, cassette_number, denomination, note_count, amount)
      VALUES (v_run_id, r.atm_id, 2, 200, v_n200, v_n200 * 200);
    END IF;
    IF v_n500 > 0 THEN
      INSERT INTO cassette_loads (run_id, atm_id, cassette_number, denomination, note_count, amount)
      VALUES (v_run_id, r.atm_id, 3, 500, v_n500, v_n500 * 500);
    END IF;
    IF v_n2000 > 0 THEN
      INSERT INTO cassette_loads (run_id, atm_id, cassette_number, denomination, note_count, amount)
      VALUES (v_run_id, r.atm_id, 4, 2000, v_n2000, v_n2000 * 2000);
    END IF;

    p_atms_assigned := p_atms_assigned + 1;
  END LOOP;

  INSERT INTO replenishment_plan_log (target_date, location_id, runs_created, atms_assigned)
  VALUES (p_target_date, p_location_id, p_runs_created, p_atms_assigned);
END;
$proc$;

COMMENT ON PROCEDURE plan_replenishment_routes(DATE, INTEGER, INTEGER, INTEGER) IS
  'Plans replenishment runs for ATMs whose forecast exceeds remaining cash, grouped by location onto vans and custodians.';

CREATE OR REPLACE FUNCTION fault_tickets_before_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF NEW.ticket_id IS NULL THEN
    NEW.ticket_id := nextval(pg_get_serial_sequence('fault_tickets', 'ticket_id'));
  END IF;
  IF NEW.ticket_no IS NULL OR btrim(NEW.ticket_no) = '' THEN
    NEW.ticket_no := 'TKT-' || lpad(NEW.ticket_id::text, 6, '0');
  END IF;
  IF NEW.opened_at IS NULL THEN
    NEW.opened_at := CURRENT_TIMESTAMP;
  END IF;
  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS trg_fault_tickets_before_insert ON fault_tickets;
CREATE TRIGGER trg_fault_tickets_before_insert
BEFORE INSERT ON fault_tickets
FOR EACH ROW
EXECUTE FUNCTION fault_tickets_before_insert();

CREATE OR REPLACE FUNCTION raise_fault_on_recon_variance()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $fn$
DECLARE
  v_code TEXT;
  v_diff NUMERIC(14,2);
  v_priority TEXT;
BEGIN
  v_diff := NEW.counted_amount - NEW.expected_amount;
  IF v_diff = 0 THEN
    RETURN NEW;
  END IF;

  SELECT atm_code INTO v_code FROM atms WHERE atm_id = NEW.atm_id;

  IF abs(v_diff) >= 100000 THEN
    v_priority := 'critical';
  ELSIF abs(v_diff) >= 10000 THEN
    v_priority := 'high';
  ELSE
    v_priority := 'medium';
  END IF;

  INSERT INTO fault_tickets (
    atm_id,
    reconciliation_id,
    title,
    description,
    category,
    priority,
    status,
    source
  ) VALUES (
    NEW.atm_id,
    NEW.reconciliation_id,
    'Cash variance — ' || COALESCE(v_code, 'ATM ' || NEW.atm_id::text),
    'Raised automatically because counted cash did not match the expected balance. Expected '
      || to_char(NEW.expected_amount, 'FM999999999990.00')
      || ', counted '
      || to_char(NEW.counted_amount, 'FM999999999990.00')
      || ', difference '
      || to_char(v_diff, 'FM999999999990.00')
      || '.',
    'cash_variance',
    v_priority,
    'open',
    'trigger'
  );

  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS trg_reconciliation_variance ON reconciliations;
CREATE TRIGGER trg_reconciliation_variance
AFTER INSERT ON reconciliations
FOR EACH ROW
EXECUTE FUNCTION raise_fault_on_recon_variance();

