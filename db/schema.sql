CREATE VIEW v_atm_downtime_mtd AS
WITH bounds AS (
  SELECT date_trunc('month', CURRENT_TIMESTAMP) AS month_start,
         CURRENT_TIMESTAMP AS period_end
),
clipped AS (
  SELECT
    d.atm_id,
    d.downtime_id,
    GREATEST(d.started_at, b.month_start) AS started_at,
    LEAST(COALESCE(d.ended_at, b.period_end), b.period_end) AS ended_at
  FROM downtime_log d
  CROSS JOIN bounds b
  WHERE d.started_at < b.period_end
    AND COALESCE(d.ended_at, b.period_end) > b.month_start
),
ordered AS (
  SELECT
    atm_id,
    downtime_id,
    started_at,
    ended_at,
    MAX(ended_at) OVER (
      PARTITION BY atm_id
      ORDER BY started_at, ended_at, downtime_id
      ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING
    ) AS prev_end
  FROM clipped
  WHERE ended_at > started_at
),
marked AS (
  SELECT
    atm_id,
    downtime_id,
    started_at,
    ended_at,
    CASE
      WHEN prev_end IS NULL OR started_at > prev_end THEN 1
      ELSE 0
    END AS new_island
  FROM ordered
),
islands AS (
  SELECT
    atm_id,
    started_at,
    ended_at,
    SUM(new_island) OVER (
      PARTITION BY atm_id
      ORDER BY started_at, ended_at, downtime_id
      ROWS UNBOUNDED PRECEDING
    ) AS island_id
  FROM marked
),
merged AS (
  SELECT atm_id, MIN(started_at) AS started_at, MAX(ended_at) AS ended_at
  FROM islands
  GROUP BY atm_id, island_id
),
per_atm AS (
  SELECT
    a.atm_id,
    COALESCE(SUM(EXTRACT(EPOCH FROM (m.ended_at - m.started_at)) / 60.0), 0) AS downtime_minutes,
    EXTRACT(EPOCH FROM (b.period_end - b.month_start)) / 60.0 AS elapsed_minutes
  FROM atms a
  CROSS JOIN bounds b
  LEFT JOIN merged m ON m.atm_id = a.atm_id
  GROUP BY a.atm_id, b.period_end, b.month_start
)
SELECT
  a.atm_id,
  a.atm_code,
  a.site_name,
  a.status,
  br.branch_id,
  br.branch_name,
  loc.location_id,
  loc.location_name,
  loc.city,
  loc.region,
  ROUND(LEAST(GREATEST(p.downtime_minutes, 0), p.elapsed_minutes)::numeric, 1) AS downtime_minutes,
  ROUND(p.elapsed_minutes::numeric, 1) AS elapsed_minutes,
  ROUND(
    LEAST(
      100,
      GREATEST(0, p.downtime_minutes / NULLIF(p.elapsed_minutes, 0) * 100)
    )::numeric,
    2
  ) AS downtime_pct
FROM per_atm p
JOIN atms a ON a.atm_id = p.atm_id
JOIN branches br ON br.branch_id = a.branch_id
JOIN locations loc ON loc.location_id = br.location_id;

CREATE VIEW v_atm_downtime_above_5pct AS
SELECT *
FROM v_atm_downtime_mtd
WHERE downtime_pct > 5;

CREATE VIEW v_van_cashout_incidents AS
WITH servicing AS (
  SELECT DISTINCT ON (ft.ticket_id)
    ft.ticket_id,
    rr.van_id
  FROM fault_tickets ft
  JOIN cassette_loads cl ON cl.atm_id = ft.atm_id
  JOIN replenishment_runs rr ON rr.run_id = cl.run_id
  WHERE ft.category = 'cash_out'
    AND rr.status <> 'cancelled'
    AND rr.planned_date <= (ft.opened_at AT TIME ZONE 'Asia/Kolkata')::date
  ORDER BY ft.ticket_id, rr.planned_date DESC, rr.run_id DESC
)
SELECT
  cv.van_id,
  cv.van_code,
  cv.registration_no,
  cv.status AS van_status,
  loc.location_id,
  loc.location_name,
  loc.city,
  COUNT(DISTINCT servicing.ticket_id) AS cashout_incidents,
  COUNT(DISTINCT route_loads.atm_id) AS atms_on_route
FROM cash_vans cv
JOIN locations loc ON loc.location_id = cv.location_id
LEFT JOIN servicing ON servicing.van_id = cv.van_id
LEFT JOIN replenishment_runs route_runs
  ON route_runs.van_id = cv.van_id AND route_runs.status <> 'cancelled'
LEFT JOIN cassette_loads route_loads ON route_loads.run_id = route_runs.run_id
