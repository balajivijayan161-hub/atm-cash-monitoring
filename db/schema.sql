  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS replenishment_requests_one_open
  ON replenishment_requests (atm_id)
  WHERE status = 'open';

CREATE TABLE IF NOT EXISTS atm_link_status (
  atm_id INTEGER PRIMARY KEY REFERENCES atms (atm_id) ON DELETE CASCADE,
  online BOOLEAN NOT NULL DEFAULT TRUE,
  offline_since TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
