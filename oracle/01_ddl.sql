-- Oracle reference DDL for the ATM cash ledger.
-- Not executed by the Node application. The running schema is db/schema.sql (PostgreSQL).
-- Targets Oracle 12c or later (identity columns and virtual columns).

CREATE TABLE locations (
  location_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_code  VARCHAR2(10)  NOT NULL,
  location_name  VARCHAR2(100) NOT NULL,
  city           VARCHAR2(80)  NOT NULL,
  state          VARCHAR2(80)  NOT NULL,
  region         VARCHAR2(40)  NOT NULL,
  CONSTRAINT locations_code_uk UNIQUE (location_code)
);

CREATE TABLE branches (
  branch_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id  NUMBER NOT NULL,
  branch_code  VARCHAR2(16)  NOT NULL,
  branch_name  VARCHAR2(120) NOT NULL,
  address      VARCHAR2(240) NOT NULL,
  ifsc_code    VARCHAR2(11)  NOT NULL,
  CONSTRAINT branches_code_uk UNIQUE (branch_code),
  CONSTRAINT branches_location_fk FOREIGN KEY (location_id) REFERENCES locations (location_id)
);

CREATE TABLE atms (
  atm_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id         NUMBER NOT NULL,
  atm_code          VARCHAR2(20) NOT NULL,
  site_name         VARCHAR2(120) NOT NULL,
  address           VARCHAR2(240) NOT NULL,
  status            VARCHAR2(20) NOT NULL,
  installed_on      DATE NOT NULL,
  cassette_count    NUMBER(1) DEFAULT 4 NOT NULL,
  capacity_amount   NUMBER(14,2) NOT NULL,
  current_cash      NUMBER(14,2) NOT NULL,
  last_replenished_on DATE,
  CONSTRAINT atms_code_uk UNIQUE (atm_code),
  CONSTRAINT atms_branch_fk FOREIGN KEY (branch_id) REFERENCES branches (branch_id),
  CONSTRAINT atms_status_ck CHECK (status IN ('active', 'cash_out', 'out_of_service', 'decommissioned')),
  CONSTRAINT atms_cash_ck CHECK (current_cash >= 0 AND current_cash <= capacity_amount),
  CONSTRAINT atms_capacity_ck CHECK (capacity_amount > 0)
);

CREATE TABLE cash_vans (
  van_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id      NUMBER NOT NULL,
  van_code         VARCHAR2(16) NOT NULL,
  registration_no  VARCHAR2(20) NOT NULL,
  capacity_amount  NUMBER(14,2) NOT NULL,
  status           VARCHAR2(20) NOT NULL,
  CONSTRAINT cash_vans_code_uk UNIQUE (van_code),
  CONSTRAINT cash_vans_reg_uk UNIQUE (registration_no),
  CONSTRAINT cash_vans_location_fk FOREIGN KEY (location_id) REFERENCES locations (location_id),
  CONSTRAINT cash_vans_status_ck CHECK (status IN ('available', 'on_route', 'maintenance'))
);

CREATE TABLE custodians (
  custodian_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  van_id         NUMBER,
  employee_code  VARCHAR2(16) NOT NULL,
  full_name      VARCHAR2(120) NOT NULL,
  phone          VARCHAR2(20) NOT NULL,
  active         NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT custodians_code_uk UNIQUE (employee_code),
  CONSTRAINT custodians_van_fk FOREIGN KEY (van_id) REFERENCES cash_vans (van_id),
  CONSTRAINT custodians_active_ck CHECK (active IN (0, 1))
);

CREATE TABLE engineers (
  engineer_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id    NUMBER NOT NULL,
  employee_code  VARCHAR2(16) NOT NULL,
  full_name      VARCHAR2(120) NOT NULL,
  phone          VARCHAR2(20) NOT NULL,
  specialty      VARCHAR2(24) NOT NULL,
  active         NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT engineers_code_uk UNIQUE (employee_code),
  CONSTRAINT engineers_location_fk FOREIGN KEY (location_id) REFERENCES locations (location_id),
  CONSTRAINT engineers_specialty_ck CHECK (specialty IN ('hardware', 'network', 'cash_handling', 'general'))
);

CREATE TABLE replenishment_runs (
  run_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  van_id        NUMBER NOT NULL,
  custodian_id  NUMBER NOT NULL,
  location_id   NUMBER NOT NULL,
  planned_date  DATE NOT NULL,
  status        VARCHAR2(20) NOT NULL,
  notes         VARCHAR2(4000),
  created_by    VARCHAR2(40) DEFAULT 'planner' NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT runs_van_fk FOREIGN KEY (van_id) REFERENCES cash_vans (van_id),
  CONSTRAINT runs_custodian_fk FOREIGN KEY (custodian_id) REFERENCES custodians (custodian_id),
  CONSTRAINT runs_location_fk FOREIGN KEY (location_id) REFERENCES locations (location_id),
  CONSTRAINT runs_status_ck CHECK (status IN ('planned', 'in_progress', 'completed', 'cancelled'))
);

CREATE TABLE cassette_loads (
  load_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id           NUMBER NOT NULL,
  atm_id           NUMBER NOT NULL,
  cassette_number  NUMBER(1) NOT NULL,
  denomination     NUMBER(10,2) NOT NULL,
  note_count       NUMBER(6) NOT NULL,
  amount           NUMBER(14,2) NOT NULL,
  loaded_at        TIMESTAMP WITH TIME ZONE,
  CONSTRAINT loads_run_fk FOREIGN KEY (run_id) REFERENCES replenishment_runs (run_id) ON DELETE CASCADE,
  CONSTRAINT loads_atm_fk FOREIGN KEY (atm_id) REFERENCES atms (atm_id),
  CONSTRAINT loads_slot_uk UNIQUE (run_id, atm_id, cassette_number),
  CONSTRAINT loads_denom_ck CHECK (denomination IN (100, 200, 500, 2000)),
  CONSTRAINT loads_notes_ck CHECK (note_count > 0 AND note_count <= 10000),
  CONSTRAINT loads_amount_ck CHECK (amount = denomination * note_count)
);

CREATE TABLE daily_withdrawals (
  withdrawal_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atm_id           NUMBER NOT NULL,
  withdrawal_date  DATE NOT NULL,
  amount           NUMBER(14,2) NOT NULL,
  txn_count        NUMBER(8) NOT NULL,
  source           VARCHAR2(20) DEFAULT 'seed' NOT NULL,
  CONSTRAINT withdrawals_atm_fk FOREIGN KEY (atm_id) REFERENCES atms (atm_id),
  CONSTRAINT withdrawals_day_uk UNIQUE (atm_id, withdrawal_date),
  CONSTRAINT withdrawals_amount_ck CHECK (amount >= 0)
);

CREATE TABLE reconciliations (
  reconciliation_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atm_id             NUMBER NOT NULL,
  run_id             NUMBER,
  recon_date         DATE NOT NULL,
  expected_amount    NUMBER(14,2) NOT NULL,
  counted_amount     NUMBER(14,2) NOT NULL,
  difference         NUMBER(14,2) GENERATED ALWAYS AS (counted_amount - expected_amount) VIRTUAL,
  notes              VARCHAR2(4000),
  created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT recon_atm_fk FOREIGN KEY (atm_id) REFERENCES atms (atm_id),
  CONSTRAINT recon_run_fk FOREIGN KEY (run_id) REFERENCES replenishment_runs (run_id)
);

CREATE SEQUENCE fault_ticket_no_seq START WITH 1;

CREATE TABLE fault_tickets (
  ticket_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_no          VARCHAR2(16) DEFAULT ('TKT-' || LPAD(fault_ticket_no_seq.NEXTVAL, 6, '0')) NOT NULL,
  atm_id             NUMBER NOT NULL,
  reconciliation_id  NUMBER,
  engineer_id        NUMBER,
  title              VARCHAR2(200) NOT NULL,
  description        VARCHAR2(4000),
  category           VARCHAR2(24) NOT NULL,
  priority           VARCHAR2(12) NOT NULL,
  status             VARCHAR2(12) NOT NULL,
  source             VARCHAR2(12) NOT NULL,
  resolution         VARCHAR2(4000),
  opened_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  assigned_at        TIMESTAMP WITH TIME ZONE,
  closed_at          TIMESTAMP WITH TIME ZONE,
  CONSTRAINT tickets_no_uk UNIQUE (ticket_no),
  CONSTRAINT tickets_atm_fk FOREIGN KEY (atm_id) REFERENCES atms (atm_id),
  CONSTRAINT tickets_recon_fk FOREIGN KEY (reconciliation_id) REFERENCES reconciliations (reconciliation_id),
  CONSTRAINT tickets_engineer_fk FOREIGN KEY (engineer_id) REFERENCES engineers (engineer_id),
  CONSTRAINT tickets_category_ck CHECK (category IN ('cash_variance', 'cash_out', 'hardware', 'communication', 'cassette_error')),
  CONSTRAINT tickets_status_ck CHECK (status IN ('open', 'assigned', 'closed')),
  CONSTRAINT tickets_source_ck CHECK (source IN ('trigger', 'manual', 'monitor'))
);

CREATE TABLE downtime_log (
  downtime_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atm_id       NUMBER NOT NULL,
  ticket_id    NUMBER,
  started_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  ended_at     TIMESTAMP WITH TIME ZONE,
  reason       VARCHAR2(24) NOT NULL,
  notes        VARCHAR2(4000),
  CONSTRAINT downtime_atm_fk FOREIGN KEY (atm_id) REFERENCES atms (atm_id),
  CONSTRAINT downtime_ticket_fk FOREIGN KEY (ticket_id) REFERENCES fault_tickets (ticket_id),
  CONSTRAINT downtime_window_ck CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE replenishment_plan_log (
  plan_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_date    DATE NOT NULL,
  location_id    NUMBER,
  runs_created   NUMBER NOT NULL,
  atms_assigned  NUMBER NOT NULL,
  planned_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT plan_log_location_fk FOREIGN KEY (location_id) REFERENCES locations (location_id)
);

CREATE INDEX withdrawals_atm_date_ix ON daily_withdrawals (atm_id, withdrawal_date);
CREATE INDEX downtime_atm_started_ix ON downtime_log (atm_id, started_at);
CREATE INDEX runs_date_ix ON replenishment_runs (planned_date);
CREATE INDEX loads_run_ix ON cassette_loads (run_id);
